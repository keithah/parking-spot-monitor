def test_detector_index_normalization_rejects_unexpected_compiler_output() -> None:
    module = load_lock_module()

    with pytest.raises(RuntimeError, match="index directives"):
        module.normalize_detector_indexes("torch==2.7.1+cpu \\\n")


def test_detector_index_normalization_restores_portable_index_order() -> None:
    module = load_lock_module()
    compiled = (
        "--index-url https://download.pytorch.org/whl/cpu\n"
        "--extra-index-url https://pypi.org/simple\n\n"
        "torch==2.7.1+cpu \\\n"
        "    --hash=sha256:" + "a" * 64 + "\n"
    )

    normalized = module.normalize_detector_indexes(compiled)

    assert normalized.startswith(
        "--index-url https://pypi.org/simple\n"
        "--extra-index-url https://download.pytorch.org/whl/cpu\n\n"
    )
    assert "torch==2.7.1+cpu" in normalized


