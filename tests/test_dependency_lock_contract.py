@pytest.mark.parametrize(
    ("relative_path", "expected_message"),
    [
        ("requirements-build.lock", "missing"),
        ("requirements-runtime.lock", "missing"),
        ("requirements-detector.lock", "missing"),
    ],
)
def test_lock_check_reports_missing_lock_without_creating_it(
    tmp_path: Path,
    relative_path: str,
    expected_message: str,
) -> None:
    root = copy_lock_inputs(tmp_path)
    lock_path = root / relative_path
    lock_path.unlink()

    completed = run_check(root)

    assert completed.returncode == 1
    assert expected_message in completed.stderr.lower()
    assert relative_path in completed.stderr
    assert not lock_path.exists()


def test_lock_check_reports_stale_locks_without_overwriting_them(tmp_path: Path) -> None:
    root = copy_lock_inputs(tmp_path)
    source = root / "requirements.txt"
    source.write_text(source.read_text(encoding="utf-8") + "sniffio>=1\n", encoding="utf-8")
    pyproject = root / "pyproject.toml"
    pyproject.write_text(
        pyproject.read_text(encoding="utf-8").replace(
            '    "PyYAML>=6",',
            '    "PyYAML>=6",\n    "sniffio>=1",',
        ),
        encoding="utf-8",
    )
    before = {
        path.name: (path.read_bytes(), hashlib.sha256(path.read_bytes()).hexdigest())
        for path in (
            root / "requirements-runtime.lock",
            root / "requirements-detector.lock",
        )
    }

    completed = run_check(root)

    assert completed.returncode == 1
    assert "stale" in completed.stderr.lower()
    assert "requirements-runtime.lock" in completed.stderr
    assert "requirements-detector.lock" in completed.stderr
    after = {
        path.name: (path.read_bytes(), hashlib.sha256(path.read_bytes()).hexdigest())
        for path in (
            root / "requirements-runtime.lock",
            root / "requirements-detector.lock",
        )
    }
    assert after == before


def test_lock_check_rejects_header_only_locks(tmp_path: Path) -> None:
    root = copy_lock_inputs(tmp_path)
    digest = load_lock_module().compute_source_digest(root)
    header = f"# This file is autogenerated.\n# source-sha256: {digest}\n"
    for path in (root / "requirements-runtime.lock", root / "requirements-detector.lock"):
        path.write_text(header, encoding="utf-8")

    completed = run_check(root)

    assert completed.returncode == 1
    assert "invalid dependency lock" in completed.stderr.lower()
    assert "requirements-runtime.lock" in completed.stderr
    assert "requirements-detector.lock" in completed.stderr


