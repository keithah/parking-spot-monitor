def test_build_tool_validation_rejects_any_pinned_version_mismatch(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    root = copy_lock_inputs(tmp_path)
    module = load_lock_module()
    expected = lock_pin_versions(
        (root / "requirements-build.lock").read_text(encoding="utf-8")
    )
    mismatched = next(iter(expected))

    monkeypatch.setattr(
        module.importlib.metadata,
        "version",
        lambda name: "0.0" if name == mismatched else expected[name],
    )

    with pytest.raises(RuntimeError, match=mismatched):
        module._validate_build_tool(root)


