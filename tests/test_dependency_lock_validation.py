@pytest.mark.parametrize(
    "broken_block",
    [
        "httpx==1.0\n" + f"    --hash=sha256:{'a' * 64}\n",
        (
            "httpx==1.0 \\\n"
            f"    --hash=sha256:{'a' * 64}\n"
            f"    --hash=sha256:{'b' * 64}\n"
        ),
        "httpx==1.0 \\\n" + f"    --hash=sha256:{'a' * 64} \\\n",
    ],
)
def test_lock_validation_rejects_broken_continuation_syntax(
    tmp_path: Path, broken_block: str
) -> None:
    root = copy_lock_inputs(tmp_path)
    module = load_lock_module()
    digest = module.compute_source_digest(root)
    text = (
        "# This file is autogenerated by scripts/lock_dependencies.py.\n"
        f"# source-sha256: {digest}\n\n"
        "--index-url https://pypi.org/simple\n\n"
        + broken_block
        + compiled_requirement("pillow")
        + compiled_requirement("pydantic")
        + compiled_requirement("pyyaml")
    )

    with pytest.raises(RuntimeError, match="continuation"):
        module._validate_lock_text(
            root,
            "requirements.txt",
            "requirements-runtime.lock",
            text,
            digest,
        )


