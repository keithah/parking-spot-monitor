def test_lock_check_reports_stale_locks_without_overwriting_them(tmp_path: Path) -> None:
    root = _copy_lock_inputs(tmp_path)
    source = root / "requirements.txt"
    source.write_text(source.read_text(encoding="utf-8") + "sniffio>=1\n", encoding="utf-8")
    pyproject = root / "pyproject.toml"
    pyproject.write_text(
        pyproject.read_text(encoding="utf-8").replace(
            '    "PyYAML>=6",',
            '    "PyYAML>=6",\n    "sniffio>=1",',
        ),
        encoding="utf-8",
    )
    before = {
        path.name: (path.read_bytes(), hashlib.sha256(path.read_bytes()).hexdigest())
        for path in (
            root / "requirements-runtime.lock",
            root / "requirements-detector.lock",
        )
    }

    completed = _run_check(root)

    assert completed.returncode == 1
    assert "stale" in completed.stderr.lower()
    assert "requirements-runtime.lock" in completed.stderr
    assert "requirements-detector.lock" in completed.stderr
    after = {
        path.name: (path.read_bytes(), hashlib.sha256(path.read_bytes()).hexdigest())
        for path in (
            root / "requirements-runtime.lock",
            root / "requirements-detector.lock",
        )
    }
    assert after == before


