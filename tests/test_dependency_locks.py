ROOT = Path(__file__).resolve().parents[1]
LOCK_SCRIPT = ROOT / "scripts" / "lock_dependencies.py"
LOCK_PATHS = (
    ROOT / "requirements-runtime.lock",
    ROOT / "requirements-detector.lock",
)


def _run_check(root: Path) -> subprocess.CompletedProcess[str]:
    environment = {
        **os.environ,
        "PIP_NO_INDEX": "1",
        "PIP_DISABLE_PIP_VERSION_CHECK": "1",
        "PYTHONNOUSERSITE": "1",
    }
    return subprocess.run(
        [sys.executable, str(root / "scripts" / "lock_dependencies.py"), "--check"],
        cwd=root,
        env=environment,
        text=True,
        capture_output=True,
        check=False,
    )


def _copy_lock_inputs(tmp_path: Path) -> Path:
    root = tmp_path / "repository"
    (root / "scripts").mkdir(parents=True)
    for relative in (
        "requirements.txt",
        "requirements-detector.txt",
        "requirements-build.txt",
        "pyproject.toml",
        "requirements-runtime.lock",
        "requirements-detector.lock",
        "scripts/lock_dependencies.py",
    ):
        source = ROOT / relative
        destination = root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    return root


def _requirement_blocks(text: str) -> list[str]:
    lines = text.splitlines()
    blocks: list[str] = []
    current: list[str] = []
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if not line.startswith((" ", "\t")) and stripped.startswith("--"):
            continue
        if not line.startswith((" ", "\t")):
            if current:
                blocks.append("\n".join(current))
            current = [stripped]
        elif current:
            current.append(stripped)
    if current:
        blocks.append("\n".join(current))
    return blocks


@pytest.mark.parametrize("path", LOCK_PATHS)
def test_lock_files_pin_and_hash_every_requirement(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    assert "autogenerated" in text.lower()
    blocks = _requirement_blocks(text)
    assert blocks
    assert all("==" in block for block in blocks)
    assert all("--hash=sha256:" in block for block in blocks)


