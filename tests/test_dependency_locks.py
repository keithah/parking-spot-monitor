def _compiled_requirement(name: str, version: str = "1.0") -> str:
    return f"{name}=={version} \\\n    --hash=sha256:{'a' * 64}\n"


def _valid_compiled(source: str) -> str:
    if source == "requirements.txt":
        # pip-tools suppresses its default PyPI directive even when supplied
        # explicitly; the generator must make the reviewed install source explicit.
        directives = ""
        requirements = ("httpx", "pillow", "pydantic", "pyyaml")
    else:
        directives = (
            "--index-url https://download.pytorch.org/whl/cpu\n"
            "--extra-index-url https://pypi.org/simple\n\n"
        )
        requirements = ("torch", "torchvision", "ultralytics")
    return directives + "".join(_compiled_requirement(name) for name in requirements)


def test_generation_sanitizes_indexes_and_publishes_explicit_sources(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    root = _copy_lock_inputs(tmp_path)
    module = _load_lock_module()
    monkeypatch.setattr(module, "_validate_build_tool", lambda _root: None)
    calls: list[tuple[list[str], dict[str, str]]] = []

    def fake_run(command, *, cwd, check, env):
        output = next(
            arg.split("=", 1)[1]
            for arg in command
            if arg.startswith("--output-file=")
        )
        source = command[-1]
        (root / output).write_text(_valid_compiled(source), encoding="utf-8")
        calls.append((command, env))
        return SimpleNamespace(returncode=0)

    monkeypatch.setattr(module.subprocess, "run", fake_run)
    monkeypatch.setenv("PIP_INDEX_URL", "https://untrusted.invalid/simple")
    monkeypatch.setenv("PIP_EXTRA_INDEX_URL", "https://also-untrusted.invalid/simple")
    monkeypatch.setenv("PIP_FIND_LINKS", "/untrusted/wheels")
    monkeypatch.setenv("PIP_NO_INDEX", "1")
    monkeypatch.setenv("PIP_TRUSTED_HOST", "untrusted.invalid")

    module.generate_locks(root)

    assert len(calls) == 2
    for command, environment in calls:
        assert command[:4] == [sys.executable, "-P", "-m", "piptools"]
        assert any(
            argument
            in (
                "--index-url=https://pypi.org/simple",
                "--index-url=https://download.pytorch.org/whl/cpu",
            )
            for argument in command
        )
        for name in (
            "PIP_INDEX_URL",
            "PIP_EXTRA_INDEX_URL",
            "PIP_FIND_LINKS",
            "PIP_NO_INDEX",
            "PIP_TRUSTED_HOST",
        ):
            assert name not in environment
        assert environment["PIP_CONFIG_FILE"] == os.devnull
        assert "PYTHONPATH" not in environment
        assert environment["PYTHONSAFEPATH"] == "1"
    assert (
        root.joinpath("requirements-runtime.lock")
        .read_text(encoding="utf-8")
        .splitlines()[3]
        == "--index-url https://pypi.org/simple"
    )
    assert (
        root.joinpath("requirements-detector.lock")
        .read_text(encoding="utf-8")
        .splitlines()[3:5]
        == [
            "--index-url https://pypi.org/simple",
            "--extra-index-url https://download.pytorch.org/whl/cpu",
        ]
    )


@pytest.mark.parametrize(
    "bad_output",
    [
        "httpx==1.0\n",
        (
            "httpx==1.0\n"
            f"    --hash=sha256:{'a' * 64}\n"
        ),
        (
            "httpx==1.0 \\\n"
            f"    --hash=sha256:{'a' * 64}\n"
            f"    --hash=sha256:{'b' * 64}\n"
        ),
        (
            "httpx==1.0 \\\n"
            f"    --hash=sha256:{'a' * 64} \\\n"
        ),
        (
            "httpx>=1.0 \\\n"
            f"    --hash=sha256:{'a' * 64}\n"
        ),
        (
            "--index-url https://unexpected.invalid/simple\n\n"
            + _compiled_requirement("httpx")
        ),
    ],
)
def test_malformed_successful_compiler_output_preserves_both_locks_and_cleans_temps(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, bad_output: str
) -> None:
    root = _copy_lock_inputs(tmp_path)
    module = _load_lock_module()
    monkeypatch.setattr(module, "_validate_build_tool", lambda _root: None)
    before = {
        name: root.joinpath(name).read_bytes()
        for name in ("requirements-runtime.lock", "requirements-detector.lock")
    }

    def fake_run(command, *, cwd, check, env):
        output = next(
            arg.split("=", 1)[1]
            for arg in command
            if arg.startswith("--output-file=")
        )
        source = command[-1]
        text = bad_output if source == "requirements.txt" else _valid_compiled(source)
        (root / output).write_text(text, encoding="utf-8")
        return SimpleNamespace(returncode=0)

    monkeypatch.setattr(module.subprocess, "run", fake_run)

    with pytest.raises(RuntimeError, match="invalid generated dependency lock"):
        module.generate_locks(root)

    after = {
        name: root.joinpath(name).read_bytes()
        for name in ("requirements-runtime.lock", "requirements-detector.lock")
    }
    assert after == before
    assert list(root.glob(".*.lock.*.tmp")) == []


